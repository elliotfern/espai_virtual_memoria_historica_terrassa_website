    <p>
        Perquè la memòria no consisteix únicament a recordar. També consisteix
        a investigar.
    </p>

    <p>
        I investigar té un cost. Cal dedicar hores a consultar documents,
        reconstruir trajectòries personals, contrastar informació i comprovar
        que les dades que publiquem siguin tan rigoroses com sigui possible.
        Quan aquesta feina es fa amb voluntat de servei públic i amb la
        intenció que el resultat sigui accessible a tothom, és important
        trobar mecanismes que permetin sostenir-la en el temps.
    </p>

    <p>
        L’EVMHT és, en aquest sentit, un projecte col·lectiu. És fruit de
        molts anys de treball i de la voluntat de preservar una part de la
        història de Terrassa que no podem deixar perdre. Però també volem
        que sigui un projecte viu, que continuï creixent i incorporant noves
        dades, nous documents i noves històries.
    </p>

    <p>
        Per això ara demanem la implicació de la ciutadania.
    </p>

    <p>
        Qualsevol persona que vulgui contribuir a aquesta tasca pot fer una
        aportació econòmica a partir de 25 euros. La campanya estarà oberta
        fins a finals de 2026 i tota la informació per col·laborar-hi es pot
        consultar a
        <a href="/donatius"><strong>memoriaterrassa.cat/donatius</strong></a>.
    </p>

    <p>
        No demanem només una aportació econòmica. Demanem suport a una manera
        d'entendre la memòria: com una responsabilitat compartida i com una
        eina de coneixement.
    </p>

    <p>
        Perquè quan recuperem el nom d’una persona que va ser represaliada,
        quan reconstruïm la seva història i quan posem aquesta informació a
        disposició de tothom, no només estem explicant què va passar fa
        vuitanta anys.
    </p>

    <p>
        Estem retornant a aquella persona un lloc dins de la història de
        Terrassa.
    </p>


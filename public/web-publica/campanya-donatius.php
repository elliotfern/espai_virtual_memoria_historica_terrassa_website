    <p>
        Què en sabem, avui, de les terrassenques i els terrassencs que van patir
        la repressió franquista? Quants noms coneixem? Quantes històries
        personals, familiars i professionals hi ha encara amagades dins dels
        expedients dels consells de guerra celebrats durant la dictadura?
        Darrere de cada història hi ha una persona: un nom, uns cognoms, una
        família, una professió, unes idees, una vida. I, en molts casos,
        també hi ha una història de repressió que durant dècades ha
        quedat amagada entre papers a l’arxiu.
    </p>

    <p>
        A Terrassa, encara tenim molta feina per fer per recuperar aquestes
        històries. Sabem que al voltant de 5.000 terrassencs i terrassenques
        van patir diferents formes de repressió durant la Guerra Civil i la
        dictadura franquista. Però conèixer aquesta xifra no és suficient.
        Cal saber qui eren, què els va passar i, sempre que sigui possible,
        posar nom i context a les seves trajectòries.
    </p>

    <p>
        Aquesta és precisament una de les tasques que, des de l’any 2024, està
        desenvolupant l’Espai Virtual de la Memòria Històrica de Terrassa,
        un projecte del Centre d’Estudis Històrics de Terrassa, que té com a
        objectiu recuperar, investigar i posar a disposició de tothom la
        memòria de la nostra ciutat durant un dels períodes més convulsos i
        dolorosos de la nostra història recent. I és una feina que continua.
    </p>

    <p>
        Ara estem treballant en el buidatge dels expedients dels consells de
        guerra franquistes corresponents a aproximadament 1.000 persones
        represaliades. Primer cal digitalitzar aquesta documentació; després,
        estudiar-la, introduir-ne les dades, contrastar-les i verificar-les
        abans de fer-les accessibles a través del web.
    </p>

    <p>
        És una feina d’investigació lenta i rigorosa. I necessita recursos.
        Hem rebut el suport institucional de l’Ajuntament de Terrassa, la
        Diputació de Barcelona i del Consell Comarcal del Vallès Occidental,
        així com dels sindicats Comissions Obreres, Unió Generals dels
        Treballadors i Confederació General del Treball. Però ara també
        necessitem el suport individual dels terrassencs i terrassenques
        per poder seguir endavant.
    </p>

    <p>
        <strong>
            Per aquest motiu, el Centre d’Estudis Històrics de Terrassa ha
            decidit impulsar una campanya de suport econòmic a l’Espai Virtual
            de la Memòria Històrica de Terrassa.
        </strong>
        No és una campanya per finançar una activitat puntual ni per assolir
        una determinada quantitat de diners.
        <strong>
            És una crida a la ciutadania perquè qui ho vulgui, pugui contribuir
            a fer possible la continuïtat d’una investigació que considerem
            necessària per a Terrassa.
        </strong>
    </p>

    <p>
        <strong>
            Les aportacions, a partir de 25 euros, es destinaran directament
            a finançar el treball dels investigadors que estan fent possible
            aquest buidatge documental
        </strong>:
        la digitalització dels expedients que es troben dipositats a l’Arxiu
        Militar a Barcelona i el posterior tractament, introducció i
        verificació de les dades que acabaran formant part de l’Espai
        Virtual de la Memòria Històrica de Terrassa.
    </p>
